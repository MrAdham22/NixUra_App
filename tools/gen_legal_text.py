#!/usr/bin/env python3
"""Generates presentation/legal/LegalContent.kt from docs/legal/*.md so the in-app Privacy Policy / Terms
screens always match the published documents. Re-run after editing the markdown:  python3 tools/gen_legal_text.py"""
import re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "shared/src/commonMain/kotlin/com/adhamelgendy/nixura/presentation/legal/LegalContent.kt"

def clean(t):
    t = re.sub(r"\*\*(.+?)\*\*", r"\1", t)
    t = re.sub(r"(?<!\*)\*(?!\*)(.+?)(?<!\*)\*(?!\*)", r"\1", t)
    t = t.replace("`", "")
    return re.sub(r"\s+", " ", t).strip()

def kt(t):
    return '"' + t.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'

def parse(md):
    lines = md.splitlines()
    blocks, i = [], 0
    while i < len(lines):
        ln = lines[i].rstrip()
        if not ln or ln.startswith("<!--"):
            i += 1; continue
        if ln.startswith("# "):
            blocks.append(("Title", clean(ln[2:])))
        elif ln.startswith("## "):
            blocks.append(("Heading", clean(ln[3:])))
        elif ln.startswith("|"):
            nxt = lines[i + 1].strip() if i + 1 < len(lines) else ""
            if re.match(r"^\|[\s:|-]+\|$", nxt):          # header row: skip it and the separator
                i += 2; continue
            cells = [clean(c) for c in ln.strip().strip("|").split("|")]
            blocks.append(("Bullet", cells[0] + ": " + " / ".join(c for c in cells[1:] if c)))
        elif ln.startswith("- "):
            blocks.append(("Bullet", clean(ln[2:])))
        elif ln.startswith("*") and ln.endswith("*") and not ln.startswith("**"):
            blocks.append(("Note", clean(ln)))
        else:
            blocks.append(("Paragraph", clean(ln)))
        i += 1
    return blocks

def emit(name, blocks):
    rows = ",\n".join(f"        LegalBlock(LegalBlockStyle.{s}, {kt(t)})" for s, t in blocks)
    return f"    val {name}: List<LegalBlock> = listOf(\n{rows},\n    )\n"

privacy = parse((ROOT / "docs/legal/PRIVACY_POLICY.md").read_text(encoding="utf-8"))
terms = parse((ROOT / "docs/legal/TERMS_OF_USE.md").read_text(encoding="utf-8"))
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(
    "// GENERATED by tools/gen_legal_text.py from docs/legal/*.md. Do not edit by hand.\n"
    "package com.adhamelgendy.nixura.presentation.legal\n\n"
    "enum class LegalBlockStyle { Title, Heading, Paragraph, Bullet, Note }\n\n"
    "data class LegalBlock(val style: LegalBlockStyle, val text: String)\n\n"
    "object LegalContent {\n" + emit("privacy", privacy) + "\n" + emit("terms", terms) + "}\n",
    encoding="utf-8",
)
print(f"wrote {OUT.relative_to(ROOT)}: privacy={len(privacy)} blocks, terms={len(terms)} blocks")
